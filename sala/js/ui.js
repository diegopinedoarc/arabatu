// Rellena los elementos con data-icon="nombre" con su SVG
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => { if (ICON[el.dataset.icon]) el.innerHTML = ICON[el.dataset.icon]; });
}

// Portada de tarjeta (miniatura de YouTube o portada violeta para Drive)
export function coverHTML(m, thumb) {
  const glyph = m.tipo === "video" ? ICON.film : ICON.note;
  return `<div class="cover"><span class="glyph">${glyph}</span>${thumb ? `<img class="thumb" src="${esc(thumb)}" alt="" loading="lazy" onerror="this.remove()">` : ""}</div>`;
}
